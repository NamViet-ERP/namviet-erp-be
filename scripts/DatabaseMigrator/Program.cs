using System.Reflection;
using System.Text;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.Extensions.Configuration;
using Npgsql;
using IdentityContext = NamViet.ERP.Modules.Identity.Infrastructure.Persistence.IdentityDbContext;
using WarehouseContext = NamViet.ERP.Modules.Warehouse.Infrastructure.Persistence.WarehouseDbContext;
using HrContext = NamViet.ERP.Modules.Hr.Infrastructure.Persistence.HrDbContext;

const string connectionStringKey = "ConnectionStrings:Default";
const string advisoryLockName = "namviet-erp-database-migrator";

using var cancellationSource = new CancellationTokenSource();
Console.CancelKeyPress += (_, eventArgs) =>
{
    eventArgs.Cancel = true;
    cancellationSource.Cancel();
};

try
{
    var configuration = new ConfigurationBuilder()
        .AddUserSecrets(Assembly.GetExecutingAssembly(), optional: true)
        .AddEnvironmentVariables()
        .Build();

    var command = ParseCommand(args);
    var connectionString = configuration[connectionStringKey];
    if (string.IsNullOrWhiteSpace(connectionString))
    {
        if (command.Name == "script")
        {
            // EF only needs provider options to render SQL; no connection is opened.
            connectionString = "Host=localhost;Database=namviet_erp;Username=script_generator";
        }
        else
        {
            throw new InvalidOperationException(
                $"{connectionStringKey} is required. Set ConnectionStrings__Default or a user secret.");
        }
    }

    return command.Name switch
    {
        "migrate" => await MigrateAsync(connectionString, cancellationSource.Token),
        "script" => await GenerateScriptAsync(connectionString, command.OutputPath, cancellationSource.Token),
        _ => throw new InvalidOperationException($"Unsupported command '{command.Name}'.")
    };
}
catch (OperationCanceledException)
{
    Console.Error.WriteLine("[migrator] Cancelled.");
    return 2;
}
catch (Exception exception)
{
    Console.Error.WriteLine($"[migrator] FAILED: {exception.Message}");
    Console.Error.WriteLine(exception);
    return 1;
}

static async Task<int> MigrateAsync(string connectionString, CancellationToken cancellationToken)
{
    Console.WriteLine("[migrator] Waiting for the deployment migration lock...");
    await using var lockConnection = new NpgsqlConnection(connectionString);
    await lockConnection.OpenAsync(cancellationToken);

    await using (var lockCommand = new NpgsqlCommand(
        "SELECT pg_advisory_lock(hashtext(@lock_name));",
        lockConnection))
    {
        lockCommand.Parameters.AddWithValue("lock_name", advisoryLockName);
        await lockCommand.ExecuteNonQueryAsync(cancellationToken);
    }

    Console.WriteLine("[migrator] Lock acquired. Applying module migrations in order.");

    try
    {
        await using var identity = CreateIdentityContext(connectionString);
        await ApplyContextAsync("Identity", identity, cancellationToken);

        await using var warehouse = CreateWarehouseContext(connectionString);
        await ApplyContextAsync("Warehouse", warehouse, cancellationToken);

        await using var hr = CreateHrContext(connectionString);
        await ApplyContextAsync("HR", hr, cancellationToken);

        Console.WriteLine("[migrator] SUCCESS: all module migrations are current.");
        return 0;
    }
    finally
    {
        await using var unlockCommand = new NpgsqlCommand(
            "SELECT pg_advisory_unlock(hashtext(@lock_name));",
            lockConnection);
        unlockCommand.Parameters.AddWithValue("lock_name", advisoryLockName);
        await unlockCommand.ExecuteNonQueryAsync(CancellationToken.None);
    }
}

static async Task ApplyContextAsync(
    string moduleName,
    DbContext context,
    CancellationToken cancellationToken)
{
    var pending = (await context.Database.GetPendingMigrationsAsync(cancellationToken)).ToArray();
    Console.WriteLine(
        pending.Length == 0
            ? $"[migrator] {moduleName}: already current."
            : $"[migrator] {moduleName}: applying {pending.Length} migration(s).");

    await context.Database.MigrateAsync(cancellationToken);
    Console.WriteLine($"[migrator] {moduleName}: complete.");
}

static async Task<int> GenerateScriptAsync(
    string connectionString,
    string outputPath,
    CancellationToken cancellationToken)
{
    var fullOutputPath = Path.GetFullPath(outputPath);
    Directory.CreateDirectory(Path.GetDirectoryName(fullOutputPath)!);

    var sql = new StringBuilder()
        .AppendLine("-- NamViet ERP idempotent database migrations")
        .AppendLine("-- Generated by scripts/DatabaseMigrator; review before production execution.")
        .AppendLine();

    await using (var identity = CreateIdentityContext(connectionString))
    {
        AppendIdempotentScript(sql, "Identity", identity);
    }

    await using (var warehouse = CreateWarehouseContext(connectionString))
    {
        AppendIdempotentScript(sql, "Warehouse", warehouse);
    }

    await using (var hr = CreateHrContext(connectionString))
    {
        AppendIdempotentScript(sql, "HR", hr);
    }

    await File.WriteAllTextAsync(fullOutputPath, sql.ToString(), new UTF8Encoding(false), cancellationToken);
    Console.WriteLine($"[migrator] Wrote idempotent SQL: {fullOutputPath}");
    return 0;
}

static void AppendIdempotentScript(StringBuilder output, string moduleName, DbContext context)
{
    Console.WriteLine($"[migrator] Generating {moduleName} SQL...");
    output.AppendLine("-- ===== " + moduleName + " =====");
    output.AppendLine(context.GetService<IMigrator>().GenerateScript(
        fromMigration: null,
        toMigration: null,
        MigrationsSqlGenerationOptions.Idempotent));
    output.AppendLine();
}

static IdentityContext CreateIdentityContext(string connectionString)
{   
    var options = new DbContextOptionsBuilder<IdentityContext>()
        .UseNpgsql(connectionString, postgres =>
            postgres.MigrationsHistoryTable("__ef_migrations_identity", "identity"))
        .Options;
    return new IdentityContext(options);
}

static WarehouseContext CreateWarehouseContext(string connectionString)
{
    var options = new DbContextOptionsBuilder<WarehouseContext>()
        .UseNpgsql(connectionString, postgres =>
            postgres.MigrationsHistoryTable("__ef_migrations_warehouse", "warehouse"))
        .Options;
    return new WarehouseContext(options);
}

static HrContext CreateHrContext(string connectionString)
{
    var options = new DbContextOptionsBuilder<HrContext>()
        .UseNpgsql(connectionString, postgres =>
            postgres.MigrationsHistoryTable("__ef_migrations_hr", "hr"))
        .Options;
    return new HrContext(options);
}

static MigratorCommand ParseCommand(string[] arguments)
{
    if (arguments.Length == 0 ||
        string.Equals(arguments[0], "migrate", StringComparison.OrdinalIgnoreCase))
    {
        return new MigratorCommand("migrate", string.Empty);
    }

    if (!string.Equals(arguments[0], "script", StringComparison.OrdinalIgnoreCase))
    {
        throw new InvalidOperationException(
            "Usage: DatabaseMigrator [migrate | script --output <path>]");
    }

    var outputIndex = Array.FindIndex(
        arguments,
        argument => string.Equals(argument, "--output", StringComparison.OrdinalIgnoreCase));

    if (outputIndex < 0 || outputIndex == arguments.Length - 1)
    {
        throw new InvalidOperationException("The script command requires --output <path>.");
    }

    return new MigratorCommand("script", arguments[outputIndex + 1]);
}

internal sealed record MigratorCommand(string Name, string OutputPath);
